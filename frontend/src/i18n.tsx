export type MessageKey = keyof (typeof messages)["fr"];

interface I18nApi {
  locale: Locale;
  languageTag: "fr-FR" | "en-US";
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, params?: Params) => string;
  formatBytes: (value: number | null, nullLabel?: string) => string;
  formatDate: (value: string | Date, options?: Intl.DateTimeFormatOptions) => string;
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string;
  apiError: (error: unknown, fallback: MessageKey) => string;
}

const I18nContext = createContext<I18nApi | null>(null);
const STORAGE_KEY = "wos.preferred-locale";

function initialLocale(): Locale {
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === "fr" || stored === "en") return stored;
  return "fr";
}

function interpolate(template: string, params: Params = {}): string {
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (match, key: string) =>
    Object.hasOwn(params, key) ? String(params[key]) : match,
  );
}

const apiErrorKeys: Record<string, MessageKey> = {
  authentication_failed: "login.failed",
  authentication_throttled: "login.throttled",
  current_password_invalid: "error.currentPassword",
  not_authenticated: "error.notAuthenticated",
  username_unavailable: "error.usernameUnavailable",
  user_workspace_unavailable: "error.workspaceUnavailable",
  user_storage_unavailable: "trash.storageUnavailable",
  file_path_invalid: "files.invalidPath",
  file_path_blocked: "files.blockedPath",
  directory_not_found: "files.missingFolder",
  trash_entry_not_found: "trash.missing",
  trash_restore_target_unavailable: "trash.restoreConflict",
  trash_integrity_failed: "trash.integrityFailed",
  trash_operation_unverified: "trash.restoreRollbackFailed",
  trash_purge_incomplete: "trash.purgeFailed",
  trash_storage_unavailable: "trash.temporarilyUnavailable",
};

const fallbackI18n: I18nApi = {
  locale: "fr",
  languageTag: "fr-FR",
  setLocale: () => undefined,
  t: (key, params) => interpolate(messages.fr[key], params),
  formatBytes: (value, nullLabel) => formatByteValue(value, nullLabel ?? "—", "fr-FR"),
  formatDate: (value, options) =>
    new Intl.DateTimeFormat("fr-FR", options).format(
      typeof value === "string" ? new Date(value) : value,
    ),
  formatNumber: (value, options) => new Intl.NumberFormat("fr-FR", options).format(value),
  apiError: (_error, fallback) => interpolate(messages.fr[fallback]),
};

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  const languageTag: I18nApi["languageTag"] = locale === "fr" ? "fr-FR" : "en-US";

  const setLocale = useCallback((nextLocale: Locale) => {
    window.localStorage.setItem(STORAGE_KEY, nextLocale);
    setLocaleState(nextLocale);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const t = useCallback(
    (key: MessageKey, params?: Params) => interpolate(messages[locale][key], params),
    [locale],
  );
  const formatBytes = useCallback(
    (value: number | null, nullLabel?: string) =>
      formatByteValue(value, nullLabel ?? "—", languageTag),
    [languageTag],
  );
  const formatDate = useCallback(
    (value: string | Date, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(languageTag, options).format(
        typeof value === "string" ? new Date(value) : value,
      ),
    [languageTag],
  );
  const formatNumber = useCallback(
    (value: number, options?: Intl.NumberFormatOptions) =>
      new Intl.NumberFormat(languageTag, options).format(value),
    [languageTag],
  );
  const apiError = useCallback(
    (error: unknown, fallback: MessageKey) => {
      if (!(error instanceof ApiError) || error.code === null) return t(fallback);
      return t(apiErrorKeys[error.code] ?? fallback);
    },
    [t],
  );

  const api = useMemo(
    () => ({ locale, languageTag, setLocale, t, formatBytes, formatDate, formatNumber, apiError }),
    [apiError, formatBytes, formatDate, formatNumber, languageTag, locale, setLocale, t],
  );

  return <I18nContext.Provider value={api}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nApi {
  const context = useContext(I18nContext);
  return context ?? fallbackI18n;
}
