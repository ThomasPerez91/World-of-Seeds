export type MessageKey = keyof (typeof messages)["fr"];

export function formatSettingIdentifier(identifier: string): string {
  const words = identifier
    .replace(/^WOS_/, "")
    .split(/[._]+/)
    .filter(Boolean)
    .map((word) => {
      const upper = word.toUpperCase();
      if (upper === "QB") return "qBittorrent";
      if (["HTTP", "TTL", "ZIP", "V2"].includes(upper)) return upper;
      return word.toLowerCase();
    });
  if (words.length === 0) return identifier;
  return `${words[0].slice(0, 1).toUpperCase()}${words[0].slice(1)} ${words.slice(1).join(" ")}`.trim();
}

interface I18nApi {
  locale: Locale;
  languageTag: "fr-FR" | "en-US";
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, params?: Params) => string;
  formatBytes: (value: number | null, nullLabel?: string) => string;
  formatDate: (value: string | Date, options?: Intl.DateTimeFormatOptions) => string;
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string;
  apiError: (error: unknown, fallback: MessageKey) => string;
}

const I18nContext = createContext<I18nApi | null>(null);
const STORAGE_KEY = "wos.preferred-locale";

function initialLocale(): Locale {
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === "fr" || stored === "en") return stored;
  return "fr";
}

function interpolate(template: string, params: Params = {}): string {
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (match, key: string) =>
    Object.hasOwn(params, key) ? String(params[key]) : match,
  );
}

